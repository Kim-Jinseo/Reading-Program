const DISTRACTORS = ['苹果', '学校', '朋友', '老师', '太阳', '桌子', '水', '书', '花', '鸟'];

function cleanMeaning(value) {
  // Definitions previously ended with an automatic pinyin gloss.  Keeping only
  // the Chinese meaning is clearer for young Chinese learners and avoids a
  // stale pinyin gloss after a correction.
  return value.trim()
    .replace(/\s*\([^)]*\)\s*$/, '')
    .replace(/\.\.\./g, '…')
    .replace(/\s*\/\s*/g, '；')
    .trim();
}

function uniqueOptions(options, answer, answerIndex) {
  const result = [];
  for (const option of options) {
    const value = String(option ?? '').trim();
    if (value && !result.includes(value)) result.push(value);
  }

  if (!result.includes(answer)) {
    result.splice(Math.max(0, Math.min(answerIndex, result.length)), 0, answer);
  }

  for (const distractor of DISTRACTORS) {
    if (result.length === 4) break;
    if (distractor !== answer && !result.includes(distractor)) result.push(distractor);
  }

  return result.slice(0, 4);
}

function reviewFile(filePath) {
  const curriculum = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let definitionChanges = 0;
  let optionFixes = 0;

  for (const [grade, gradeData] of Object.entries(curriculum)) {
    for (const item of gradeData.vocab ?? []) {
      const oldAnswer = String(item.answer ?? '').trim();
      const meaning = CORRECTIONS[grade]?.[item.id] ?? cleanMeaning(oldAnswer);
      const answerIndex = (item.options ?? []).findIndex(option => option === oldAnswer);
      const revisedOptions = uniqueOptions(
        (item.options ?? []).map(option => option === oldAnswer ? meaning : option),
        meaning,
        answerIndex
      );

      if (item.def !== meaning || item.answer !== meaning) definitionChanges++;
      if (JSON.stringify(item.options) !== JSON.stringify(revisedOptions)) optionFixes++;

      item.def = meaning;
      item.answer = meaning;
      item.options = revisedOptions;
    }
  }

  const entries = Object.values(curriculum).flatMap(grade => grade.vocab ?? []);
  const invalid = entries.filter(item =>
    !item.word || !/[\u4e00-\u9fff]/.test(item.def) || item.def !== item.answer ||
    item.options.length !== 4 || new Set(item.options).size !== 4 || !item.options.includes(item.answer)
  );
  if (invalid.length) throw new Error(`Vocabulary review failed for ${invalid.length} entries.`);

  fs.writeFileSync(filePath, `${JSON.stringify(curriculum, null, 2)}\n`, 'utf8');
  return { entries: entries.length, definitionChanges, optionFixes };
}

const files = ['backend/curriculum.json', 'frontend/user-app/src/data/curriculum.json'];
const results = files.map(reviewFile);
if (JSON.stringify(results[0]) !== JSON.stringify(results[1])) {
  throw new Error('Backend and frontend vocabulary results do not match.');
}


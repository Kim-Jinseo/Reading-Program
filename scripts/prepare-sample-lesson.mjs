import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const workspace = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dependencyRoot = process.env.RUNTIME_NODE_MODULES || path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules');
const require = createRequire(path.join(dependencyRoot, 'package.json'));
const sharp = require('sharp');
const artifactRoot = path.join(workspace, 'artifacts', 'class-lessons');
const sourceRenders = path.join(artifactRoot, 'source-renders');
const selectedSlides = [8, 6, 12, 14, 17, 18, 20, 24];
const mode = process.argv[2] || 'contact';

if (mode === 'contact') {
  for (let group = 0; group < 3; group += 1) {
    const items = [];
    for (let offset = 0; offset < 9; offset += 1) {
      const slide = group * 9 + offset + 1;
      const input = await sharp(path.join(sourceRenders, `slide-${String(slide).padStart(2, '0')}.png`)).resize(480, 270).toBuffer();
      items.push({ input, left: (offset % 3) * 480, top: Math.floor(offset / 3) * 270 });
    }
    await sharp({ create: { width: 1440, height: 810, channels: 3, background: '#ffffff' } })
      .composite(items).png().toFile(path.join(artifactRoot, `source-contact-${group + 1}.png`));
  }
  console.log('Created three source contact sheets in slide order, 1–9, 10–18, 19–27.');
} else if (mode === 'prepare') {
  const optimizedDirectory = path.join(artifactRoot, 'optimized');
  await fs.mkdir(optimizedDirectory, { recursive: true });
  const assets = [];
  const manifest = [];
  for (let index = 0; index < selectedSlides.length; index += 1) {
    const sourceSlide = selectedSlides[index];
    const source = path.join(artifactRoot, 'student-renders', `slide-${String(sourceSlide).padStart(2, '0')}.png`);
    const data = await sharp(source).resize(1440, 810).webp({ quality: 86, effort: 6 }).toBuffer();
    assert.ok(data.byteLength < 600_000, `Source slide ${sourceSlide} exceeds the per-image budget.`);
    const filename = `slide-${String(index + 1).padStart(2, '0')}.webp`;
    await fs.writeFile(path.join(optimizedDirectory, filename), data);
    assets.push({ _id: `sample-classroom-slide-${index + 1}`, mime: 'image/webp', data: data.toString('base64'), bytes: data.byteLength });
    manifest.push({ page: index + 1, sourceSlide, filename, bytes: data.byteLength, width: 1440, height: 810 });
  }
  const totalBytes = assets.reduce((sum, asset) => sum + asset.bytes, 0);
  assert.ok(totalBytes <= 2_000_000, 'The eight-image preview exceeds its total budget.');
  const mediaModule = '// Generated by scripts/prepare-sample-lesson.mjs prepare. Do not edit base64 by hand.\nexport const sampleAssets = ' + JSON.stringify(assets, null, 2) + ';\n';
  await fs.writeFile(path.join(workspace, 'server', 'sampleLessonMedia.js'), mediaModule);
  await fs.writeFile(path.join(artifactRoot, 'manifest.json'), JSON.stringify({ totalBytes, mediaModuleBytes: Buffer.byteLength(mediaModule), pages: manifest }, null, 2) + '\n');
  console.log(JSON.stringify({ totalBytes, mediaModuleBytes: Buffer.byteLength(mediaModule), pages: manifest }, null, 2));
} else if (mode === 'verify') {
  const modulePath = path.join(workspace, 'server', 'sampleLesson.js');
  assert.ok(await fs.access(modulePath).then(() => true, () => false), 'The sample lesson module exists.');
  const { sampleCollection, sampleLesson, sampleAssets } = await import(pathToFileURL(modulePath).href);
  assert.deepEqual(sampleCollection, { _id: 'sample-summer-2026-l2', season: 'summer', year: 2026, level: 2 });
  assert.equal(sampleLesson._id, 'sample-classroom-l2-1');
  assert.equal(sampleLesson.collectionId, sampleCollection._id);
  assert.equal(sampleLesson.level, 2);
  assert.equal(sampleLesson.number, 1);
  assert.equal(sampleLesson.title, 'Our classroom');
  assert.equal(sampleLesson.titleZh, '我们的教室');
  assert.equal(sampleLesson.slides.length, 8);
  assert.equal(sampleAssets.length, sampleLesson.slides.length);
  assert.equal(sampleLesson.vocabulary.length, 4);
  assert.equal(sampleLesson.questions.length, 3);
  for (const question of [...sampleLesson.vocabulary, ...sampleLesson.questions]) {
    assert.ok(question.id && question.prompt && question.explanation);
    assert.equal(question.options.length, 3);
    assert.equal(new Set(question.options.map(option => option.id)).size, 3);
    assert.equal(new Set(question.options.map(option => option.text)).size, 3);
    assert.equal(question.options.filter(option => option.id === question.correctOptionId).length, 1);
  }
  for (const word of ['desk', 'chair', 'blackboard', 'fan']) {
    assert.ok(sampleLesson.vocabulary.some(question => question.prompt.includes(`“${word}”`)));
  }
  assert.ok(sampleLesson.questions.every(question => /^(Who|What|Where|When)\b/.test(question.prompt)));
  assert.ok(sampleLesson.speaking.sentence && sampleLesson.speaking.hintZh);
  assert.ok(sampleLesson.writing.prompt && sampleLesson.writing.promptZh);
  assert.deepEqual(sampleLesson.writing.starters, ['There is a ...', 'There are ...', 'I like ... because ...']);
  let totalBytes = 0;
  for (let index = 0; index < sampleAssets.length; index += 1) {
    const asset = sampleAssets[index];
    const slide = sampleLesson.slides[index];
    assert.equal(asset._id, `sample-classroom-slide-${index + 1}`);
    assert.equal(slide.id, asset._id);
    assert.ok(slide.alt.length > 20);
    assert.ok(['image/webp', 'image/jpeg'].includes(asset.mime));
    const image = Buffer.from(asset.data, 'base64');
    assert.equal(image.byteLength, asset.bytes);
    assert.ok(image.byteLength < 600_000);
    const decoded = await sharp(image).metadata();
    assert.equal(decoded.width, 1440);
    assert.equal(decoded.height, 810);
    assert.equal(`image/${decoded.format}`, asset.mime);
    await sharp(image).raw().toBuffer();
    totalBytes += asset.bytes;
  }
  assert.ok(totalBytes <= 2_000_000);
  console.log(`Verified ${sampleAssets.length} decoded slide images, ${sampleLesson.vocabulary.length} vocabulary items, ${sampleLesson.questions.length} comprehension questions. Total image bytes: ${totalBytes}.`);
} else {
  assert.fail(`Unknown mode: ${mode}`);
}
